import {spawn} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const args=process.argv.slice(2);const pagesRoot=args[0]==='--pages-root';if(pagesRoot)args.shift();
const runtime=path.join(root,'.runtime');fs.mkdirSync(runtime,{recursive:true});
const child=spawn(process.execPath,[path.join(root,'node_modules/wrangler/bin/wrangler.js'),...args],{cwd:pagesRoot?path.join(root,'pages'):process.cwd(),stdio:'inherit',env:{...process.env,XDG_CONFIG_HOME:process.env.XDG_CONFIG_HOME||path.join(runtime,'config'),WRANGLER_LOG_PATH:path.join(runtime,'wrangler.log'),WRANGLER_SEND_METRICS:'false'}});
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>child.kill(signal));
child.on('error',error=>{console.error(error.message);process.exitCode=1;});child.on('exit',(code,signal)=>{process.exitCode=code??(signal==='SIGINT'?130:1);});
